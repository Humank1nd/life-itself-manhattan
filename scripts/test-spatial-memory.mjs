import assert from 'node:assert/strict';
import {readFileSync}from'node:fs';
import {performance}from'node:perf_hooks';
import {validateSpatialMemory,createSpatialMemoryIndex,retrieveSpatialMemory,createMemoryGrid}from'../src/spatial-memory.js';
const load=f=>JSON.parse(readFileSync(new URL('../'+f,import.meta.url),'utf8'));
const data=load('data/spatial-memory-v1.json'),evidence=load('data/evidence-v1.json'),
 versions=load('data/times-square-building-versions-v1.json'),catalog=load('data/photo-catalog-v1.json');
const metrics=validateSpatialMemory(data);
assert.equal(metrics.photos,69);
assert.ok(metrics.planes>4000 && metrics.planes<15000);
const known=new Set([...catalog.records.map(x=>x.id),...evidence.photos.map(x=>x.id)]);
assert.ok(data.photos.every(p=>known.has(p.id)));
const sourceIds=new Set(versions.versions.map(v=>v.id));
assert.ok(data.planes.every(p=>sourceIds.has(p.versionId)));
assert.ok(data.photos.every(p=>p.poseStatus==='not-calibrated'));
const index=createSpatialMemoryIndex(data),opts={focus:[0,0],radiusM:320,camera:[450,350,650],lookAt:[0,0,0],coneCos:0.65};
const current=retrieveSpatialMemory(index,{...opts,year:2026});
assert.ok(current.planes.length>0);
assert.ok(current.planes.length<=220);
assert.equal(current.photos.length,0);
assert.ok(current.planes.every(p=>p.snapshotAt==='2026-10-28'));
const historical=retrieveSpatialMemory(index,{...opts,year:2005});
assert.ok(historical.photos.some(p=>p.id==='commons-1284794'));
assert.equal(historical.planes.length,0,'must not show current geom for historic 2005');
assert.equal(historical.geometryStatus,'historical-geometry-unavailable');
assert.equal(historical.occlusion,'unknown');
const noEvidence=retrieveSpatialMemory(index,{...opts,year:1995});
assert.equal(noEvidence.planes.length,0);assert.equal(noEvidence.photos.length,0);
const tight=retrieveSpatialMemory(index,{...opts,year:2005,maxPhotos:1});
assert.ok(tight.photos.length<=1);
const away=retrieveSpatialMemory(index,{...opts,focus:[10000,10000],year:2005});
assert.equal(away.photos.length,0);
const turned=retrieveSpatialMemory(index,{...opts,year:2005,lookAt:[900,350,1300],coneCos:.9});
assert.equal(turned.photos.length,0,'backward view retrieval should not present images in front');
const cloned=structuredClone(data);
cloned.photos[0].poseStatus='calibrated';
assert.throws(()=>validateSpatialMemory(cloned));
cloned.photos[0].poseStatus='not-calibrated';
cloned.photos[0].trainingPermission='approved';
assert.throws(()=>validateSpatialMemory(cloned));
cloned.photos[0].trainingPermission='unreviewed';
cloned.photos[0].year=1983;
assert.throws(()=>validateSpatialMemory(cloned));
const bad=structuredClone(data);
bad.planes[0].snapshotAt='1995-01-01';
assert.throws(()=>validateSpatialMemory(bad));
assert.throws(()=>retrieveSpatialMemory(index,{...opts,year:2005,radiusM:100000}));
assert.throws(()=>createMemoryGrid([{center:[3,5]}]));
// Test strict limits and measurements on representative queries, no performance guarantees.
const start=performance.now();for(let i=0;i<200;i++)retrieveSpatialMemory(index,{...opts,year:i%2?2005:2026});
const elapsed=performance.now()-start;
console.log('PASS: source-grounded '+metrics.planes+' planes / '+metrics.photos+
 ' photos, 200 viewpoint queries in '+elapsed.toFixed(1)+'ms; historical geometry withheld, provenance/pose/training gate tests passed');
